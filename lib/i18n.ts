export function productName(id: ProductId, locale: Locale): string {
  return PRODUCT_NAMES[id][locale];
}

export function spokenAnnouncement(id: ProductId, locale: Locale): string {
  const name = productName(id, locale);
  const price = SPOKEN_PRICE[id][locale];
  const formatted = formatPrice(PRODUCTS[id].amountCents, locale);
  const templates: Record<Locale, string> = {
    en: `${name}. ${price}. That is ${formatted}.`,
    es: `${name}. ${price}. Son ${formatted}.`,
    fr: `${name}. ${price}. Soit ${formatted}.`,
    de: `${name}. ${price}. Das sind ${formatted}.`,
    pt: `${name}. ${price}. Isso é ${formatted}.`,
    zh: `${name}。${price}。即 ${formatted}。`,
    ja: `${name}。${price}。${formatted}です。`,
    hi: `${name}। ${price}। यानी ${formatted}।`,
    ar: `${name}. ${price}. أي ${formatted}.`,
    ko: `${name}. ${price}. ${formatted}입니다.`,
  };
  return templates[locale];
}

export function formatPrice(amountCents: number, locale: Locale): string {
  const localeMap: Record<Locale, string> = {
    en: "en-US",
    es: "es-ES",
    fr: "fr-FR",
    de: "de-DE",
    pt: "pt-BR",
    zh: "zh-CN",
    ja: "ja-JP",
    hi: "hi-IN",
    ar: "ar-SA",
    ko: "ko-KR",
  };
  return new Intl.NumberFormat(localeMap[locale], {
    style: "currency",
    currency: "USD",
  }).format(amountCents / 100);
}

